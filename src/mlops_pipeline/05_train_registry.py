import json
import os
import pickle

import mlflow
import mlflow.sklearn
import numpy as np
import yaml

from sklearn.ensemble import RandomForestClassifier


def load_config():
    with open("config.yaml", "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def train_and_register_model():
    config = load_config()

    # ---------------------------------------------------------
    # Configuration
    # ---------------------------------------------------------
    tracking_uri = config["mlflow"]["tracking_uri"]
    experiment_name = config["mlflow"]["experiment_name"]
    model_name = config["registry"]["model_name"]

    processed_dir = config["data"]["processed_dir"]

    model_path = config["paths"]["model"]
    preprocessor_path = config["paths"]["preprocessor"]

    model_config = config["model"]

    # ---------------------------------------------------------
    # MLflow configuration
    # ---------------------------------------------------------
    mlflow.set_tracking_uri(tracking_uri)
    mlflow.set_experiment(experiment_name)

    print("=" * 70)
    print("TRAINING + MLFLOW MODEL REGISTRATION")
    print("=" * 70)

    # ---------------------------------------------------------
    # Load processed training data
    # ---------------------------------------------------------
    # These are the actual files generated by 03_preprocessing.py
    X_train_path = os.path.join(
        processed_dir,
        "X_train_final.npy"
    )

    y_train_path = os.path.join(
        processed_dir,
        "y_train.npy"
    )

    if not os.path.exists(X_train_path):
        raise FileNotFoundError(
            f"Training data not found: {X_train_path}"
        )

    if not os.path.exists(y_train_path):
        raise FileNotFoundError(
            f"Training labels not found: {y_train_path}"
        )

    X_train = np.load(X_train_path)
    y_train = np.load(y_train_path)

    print(f"[INFO] X_train shape: {X_train.shape}")
    print(f"[INFO] y_train shape: {y_train.shape}")

    # ---------------------------------------------------------
    # Create Random Forest model
    # ---------------------------------------------------------
    model = RandomForestClassifier(
        n_estimators=model_config.get("n_estimators", 200),
        max_depth=model_config.get("max_depth", 10),
        random_state=model_config.get("random_state", 42),
        class_weight=model_config.get(
            "class_weight",
            "balanced"
        )
    )

    # ---------------------------------------------------------
    # Start MLflow run
    # ---------------------------------------------------------
    with mlflow.start_run() as run:

        print(f"[INFO] MLflow Run ID: {run.info.run_id}")

        # -----------------------------------------------------
        # Train model
        # -----------------------------------------------------
        print("[INFO] Training Random Forest model...")

        model.fit(X_train, y_train)

        print("[INFO] Model training completed.")

        # -----------------------------------------------------
        # Training accuracy
        # -----------------------------------------------------
        train_accuracy = model.score(
            X_train,
            y_train
        )

        print(
            f"[INFO] Training accuracy: "
            f"{train_accuracy:.4f}"
        )

        # -----------------------------------------------------
        # Log parameters
        # -----------------------------------------------------
        mlflow.log_param(
            "n_estimators",
            model_config.get("n_estimators", 200)
        )

        mlflow.log_param(
            "max_depth",
            model_config.get("max_depth", 10)
        )

        mlflow.log_param(
            "random_state",
            model_config.get("random_state", 42)
        )

        mlflow.log_param(
            "class_weight",
            model_config.get(
                "class_weight",
                "balanced"
            )
        )

        # -----------------------------------------------------
        # Log metrics
        # -----------------------------------------------------
        mlflow.log_metric(
            "training_accuracy",
            float(train_accuracy)
        )

        # -----------------------------------------------------
        # Save local model
        # -----------------------------------------------------
        model_directory = os.path.dirname(model_path)

        if model_directory:
            os.makedirs(
                model_directory,
                exist_ok=True
            )

        with open(model_path, "wb") as f:
            pickle.dump(model, f)

        print(
            f"[INFO] Model saved to: "
            f"{model_path}"
        )

        # -----------------------------------------------------
        # Log local model
        # -----------------------------------------------------
        mlflow.log_artifact(
            model_path,
            artifact_path="local_model"
        )

        # -----------------------------------------------------
        # Log preprocessing artifact
        # -----------------------------------------------------
        if os.path.exists(preprocessor_path):

            mlflow.log_artifact(
                preprocessor_path,
                artifact_path="preprocessing_pipeline"
            )

            print(
                f"[INFO] Preprocessor logged: "
                f"{preprocessor_path}"
            )

        else:

            print(
                f"[WARNING] Preprocessor not found: "
                f"{preprocessor_path}"
            )

        # -----------------------------------------------------
        # Log and register sklearn model
        #
        # RandomForestClassifier contains:
        # sklearn.tree._tree.Tree
        #
        # Newer MLflow/skops versions require this type to be
        # explicitly trusted.
        # -----------------------------------------------------
        print(
            "[INFO] Logging sklearn model to MLflow..."
        )

        mlflow.sklearn.log_model(
            model,
            artifact_path="model",
            registered_model_name=model_name,
            skops_trusted_types=[
                "sklearn.tree._tree.Tree"
            ]
        )

        print(
            "[INFO] Model logged to MLflow."
        )

        print(
            f"[INFO] Registered model name: "
            f"{model_name}"
        )

        # -----------------------------------------------------
        # Training report
        # -----------------------------------------------------
        report = {
            "run_id": run.info.run_id,
            "experiment_name": experiment_name,
            "registered_model_name": model_name,
            "model_type": "RandomForestClassifier",
            "training_accuracy": float(train_accuracy),
            "n_estimators": model_config.get(
                "n_estimators",
                200
            ),
            "max_depth": model_config.get(
                "max_depth",
                10
            ),
            "random_state": model_config.get(
                "random_state",
                42
            ),
            "class_weight": model_config.get(
                "class_weight",
                "balanced"
            ),
            "training_data": X_train_path,
            "training_labels": y_train_path
        }

        os.makedirs(
            "artifacts",
            exist_ok=True
        )

        report_path = (
            "artifacts/"
            "training_registry_report.json"
        )

        with open(
            report_path,
            "w",
            encoding="utf-8"
        ) as f:
            json.dump(
                report,
                f,
                indent=2
            )

        print(
            f"[INFO] Training report saved: "
            f"{report_path}"
        )

    print("=" * 70)
    print(
        "TRAINING + MLFLOW MODEL REGISTRATION "
        "COMPLETED"
    )
    print("=" * 70)

    return True


if __name__ == "__main__":

    try:

        passed = train_and_register_model()

        if passed:
            print(
                "[SUCCESS] Training and registration "
                "passed."
            )
            raise SystemExit(0)

        print(
            "[ERROR] Training and registration failed."
        )
        raise SystemExit(1)

    except Exception as e:

        print(f"[ERROR] {e}")
        raise